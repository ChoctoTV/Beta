function startChat() {
  if (!CHANNEL) { console.warn('[Chat] TWITCH_CHANNEL not set'); return; }
  if (!OAUTH_TOKEN || OAUTH_TOKEN === 'oauth:') { console.warn('[Chat] No OAuth token — read-only mode'); }

  const opts = {
    options: { debug: true },
    connection: { reconnect:true, secure:true, maxReconnectAttempts:Infinity },
    channels: [`#${CHANNEL}`],
  };

  if (BOT_NAME && OAUTH_TOKEN && OAUTH_TOKEN !== 'oauth:') {
    opts.identity = { username:BOT_NAME, password:OAUTH_TOKEN };
    console.log(`[Chat] Authenticating as ${BOT_NAME}`);
  } else {
    console.warn('[Chat] No credentials — commands will not work. Run: node setup.js');
  }

  _client = new tmi.Client(opts);

  _client.on('message', async (_ch, tags, message, self) => {
    if (self) return;
    const text = (message || '').trim();
    if (!text) return;

    const user  = (tags['display-name'] || tags.username || 'anon').toLowerCase();
    const isMod_ = !!(tags.mod || tags['user-type']==='mod' || tags.badges?.broadcaster || tags.badges?.moderator || user === CHANNEL);
    const isSub  = !!tags.subscriber;

    lurk_touch(user);
    markActive(user);

    // ── Natural language checks (music vote + gauntlet) ────────────────────────
    const msgLower = text.toLowerCase();
    const tLower   = msgLower;

    // Music vote — 3 unique viewers in 10 min toggles music
    if (!isMod_) {
      const voteOff = /music\s+off|turn\s+off\s+(?:the\s+)?music|stop\s+(?:the\s+)?music/.test(tLower);
      const voteOn  = /music\s+on|turn\s+(?:the\s+)?music\s+on|start\s+(?:the\s+)?music/.test(tLower);
      if (voteOff || voteOn) {
        const dir       = voteOff ? 'off' : 'on';
        const triggered = recordMusicVote(user, dir);
        const count     = musicVotes[dir].size;
        if (triggered) {
          music_send(dir);
          say(`🗳️ Vote passed! Music turned ${dir} by community vote (${VOTE_NEEDED}/${VOTE_NEEDED}) 🎵`);
          broadcast({ type:'music_vote', direction:dir, passed:true });
        } else {
          say(`🗳️ @${user} voted music ${dir} (${count}/${VOTE_NEEDED} votes — ${VOTE_NEEDED - count} more needed in 10 min)`);
          broadcast({ type:'music_vote', direction:dir, count, needed:VOTE_NEEDED });
        }
        return;
      }
    }

    // Gauntlet NL trigger — only if not starting with !
    if (!text.startsWith('!')) {
      const wantsGauntlet = /i\s+(want|wanna|wish)\s+to\s+run\s+(the\s+)?gauntlet/i.test(text);
      if (wantsGauntlet) {
        if (onCooldown(user, isMod_, isSub)) return;
        handleCommand('gauntlet', user, [], isMod_).catch(()=>{});
        return;
      }
    }

    // ── ! commands ────────────────────────────────────────────────────────────
    if (text.startsWith('!')) {
      const parts = text.slice(1).trim().split(/\s+/);
      const raw   = parts[0].toLowerCase();
      const cmd   = CONJ[raw] || raw;
      const args  = parts.slice(1);
      if (!KNOWN_CMDS.has(cmd)) return;
      if (['update','addcoin','removecoin','hotfix','config'].includes(cmd) && !isMod_) return;
        if (onCooldown(user, isMod_, isSub)) return;
      console.log(`[Chat] !${cmd}${args.length?' '+args.join(' '):''} ← @${user}`);
      try { await handleCommand(cmd, user, args, isMod_); } catch(e) { console.error('[Chat] Error:', e.message); }
      return;
    }

    // ── Natural language ──────────────────────────────────────────────────────
    for (const rule of NL_RULES) {
      if (!text.match(rule.re)) continue;
      if (onCooldown(user, isMod_, isSub)) return;
      const args = [];
      console.log(`[Chat] NL:${rule.cmd} ← @${user} "${text.slice(0,60)}"`);
      try { await handleCommand(rule.cmd, user, args, isMod_); } catch(e) { console.error('[Chat] Error:', e.message); }
      return;
    }
  });

  _client.on('connected',    (h, p)  => console.log(`[Chat] Connected → ${h}:${p} | #${CHANNEL}`));
  _client.on('disconnected', reason  => {
    console.warn('[Chat] Disconnected:', reason);
    if (reason && /no response|login|auth|improperly/i.test(reason)) {
      console.error('[Chat] ⚠ Token rejected. Run: node setup.js');
    }
  });
  _client.on('reconnect',    ()      => console.log('[Chat] Reconnecting...'));

  _client.connect().catch(e => console.error('[Chat] Connect failed:', e.message || e));
}

