// ── Persist helper ────────────────────────────────────────────────────────────
function makePersist(file, defaultVal) {
  let data    = defaultVal;
  let timer   = null;
  const full  = path.join(DATA_DIR, file);
  try { data = { ...defaultVal, ...JSON.parse(fs.readFileSync(full, 'utf8')) }; } catch {}
  const save = () => {
    if (timer) clearTimeout(timer);
    timer = setTimeout(() => {
      try { fs.writeFileSync(full, JSON.stringify(data, null, 2)); } catch(e) { console.error(`[persist] ${file}:`, e.message); }
    }, 500);
  };
  return { data, save, get: k => data[k], set: (k, v) => { data[k] = v; save(); } };
}

