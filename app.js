// ── Music vote tracker ───────────────────────────────────────────────────────
const musicVotes = { on: new Map(), off: new Map() }; // user → timestamp
const VOTE_WINDOW  = 10 * 60 * 1000; // 10 minutes
const VOTE_NEEDED  = 3;

function recordMusicVote(user, direction) {
  const now = Date.now();
  const map = musicVotes[direction];
  const opp = musicVotes[direction === 'on' ? 'off' : 'on'];

  // Clear expired votes
  for (const [u, ts] of map) if (now - ts > VOTE_WINDOW) map.delete(u);
  for (const [u, ts] of opp) if (now - ts > VOTE_WINDOW) opp.delete(u);

  map.set(user, now); // one vote per user (overwrites their previous)

  if (map.size >= VOTE_NEEDED) {
    map.clear(); opp.clear();
    return true; // threshold reached
  }
  return false;
}

